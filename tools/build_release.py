"""Deterministic source/evidence archive with exact manifest and unsigned digest."""

import argparse
import gzip
import hashlib
import io
import json
from pathlib import Path
import tarfile


def members(root):
    files = []
    for path in root.rglob("*"):
        if path.is_symlink() or not (path.is_file() or path.is_dir()):
            raise ValueError("release must not contain links or special files")
        if path.is_file():
            name = path.relative_to(root).as_posix()
            if "__pycache__" in path.parts or path.suffix == ".pyc" or ".git" in path.parts:
                raise ValueError("remove generated bytecode/git metadata before packaging")
            files.append((name, path))
    return sorted(files)


def build(root, output, update_manifest=False):
    root = root.resolve(strict=True)
    output = output.resolve()
    sidecar = output.with_suffix(output.suffix + ".sha256")
    if output.exists() or output.is_symlink() or output.is_relative_to(root) or sidecar.exists() or sidecar.is_symlink():
        raise ValueError("archive and digest must be fresh and outside release tree")
    files = [(name, path) for name, path in members(root) if name != "SHA256SUMS"]
    manifest = "".join(hashlib.sha256(path.read_bytes()).hexdigest() + "  " + name + "\n" for name, path in files)
    manifest_path = root / "SHA256SUMS"
    if manifest_path.exists() and not update_manifest:
        # Never silently rewrite the published manifest. Re-running a build over
        # an unchanged tree stays idempotent; a drifted tree needs an explicit flag.
        if manifest_path.read_text() != manifest:
            raise ValueError("existing SHA256SUMS no longer matches the tree; "
                             "pass --update-manifest to regenerate it deliberately")
    manifest_path.write_text(manifest)
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("xb") as stream:
        with gzip.GzipFile(fileobj=stream, mode="wb", filename="", mtime=0, compresslevel=9) as compressed:
            with tarfile.open(fileobj=compressed, mode="w", format=tarfile.PAX_FORMAT) as archive:
                for name, path in members(root):
                    payload = path.read_bytes()
                    info = tarfile.TarInfo(root.name + "/" + name)
                    info.size = len(payload)
                    info.mode = 0o644
                    info.mtime = 0
                    info.uid = info.gid = 0
                    info.uname = info.gname = ""
                    archive.addfile(info, io.BytesIO(payload))
    sha = hashlib.sha256(output.read_bytes()).hexdigest()
    with sidecar.open("x") as stream:
        stream.write(sha + "  " + output.name + "\n")
    return {"archive": str(output), "sha256": sha, "files": len(members(root)),
            "bytes": output.stat().st_size, "signature": "NOT_PROVIDED"}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--update-manifest", action="store_true",
                        help="deliberately regenerate an existing SHA256SUMS in place")
    args = parser.parse_args()
    try:
        print(json.dumps(build(args.root, args.output, args.update_manifest), indent=2))
    except (OSError, ValueError) as error:
        parser.error(str(error))
